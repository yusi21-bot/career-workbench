export function companyCategories(company: Company): CompanyCategory[] {
  if (company.categories?.length) return Array.from(new Set(company.categories));
  const found = explicit[company.name];
  if (found) return found;
  const text = `${company.name} ${company.industry} ${company.subIndustry}`;
  const result: CompanyCategory[] = [];
  if (company.industry === '文化游戏' || /游戏|电竞/.test(text)) result.push('游戏内容');
  if (company.industry === '金融证券' || /银行|证券|投资|量化|基金/.test(text)) result.push('金融投资');
  if (company.industry === '消费电子' || company.industry === '科技制造' || /硬件|芯片|半导体|机器人|汽车|能源|光电|制造/.test(text)) result.push('硬件制造');
  if (company.industry === '互联网' || /软件|AI|算法|云|网络安全|数据|科技研发|互联网/.test(text)) result.push('软件服务');
  if (company.nature === '央企国企' || company.nature === '国有控股') result.push('央国企/事业单位');
  return Array.from(new Set(result));
}

export function hasCompanyCategory(company: Company, category: CompanyCategory) {
  return companyCategories(company).includes(category);
}
